const hint = (o) => (o.type === "enum" ? o.values.join(" \\| ") : o.type === "boolean" ? "true \\| false" : "text");
const textOutput = (m) => /^text\/|json|xml/.test(m.output.contentType);

const exampleOption = (options) => {
  const o = options.find((x) => x.type !== "string");
  if (!o) return "";
  return ` -O ${o.id}=${o.type === "enum" ? o.values.find((v) => v !== o.default) : !o.default}`;
};

function section(m, engines) {
  const input = m.input.kind === "text" ? `text (${m.input.accept.join(" ")})` : `file (${m.input.accept.join(" ")}), up to ${((m.input.maxBytes ?? 1_048_576) / 1_048_576).toFixed(0)} MB`;
  const needs = engines.length ? engines.map((e) => `${e.id} (${e.license ?? "see homepage"})`).join(", ") : "nothing to install";
  const options = m.options ?? [];
  const out = textOutput(m) ? "-" : `output.${m.output.extension}`;
  return [
    `## ${m.icon} ${m.name} (\`${m.id}\`)`,
    "",
    m.description,
    ...(m.useWhen ? ["", `**Use when:** ${m.useWhen}`] : []),
    "",
    `- Reads: ${input}`,
    `- Writes: .${m.output.extension} (\`${m.output.contentType}\`)`,
    `- Needs: ${needs}`,
    ...(options.length
      ? [
          "",
          "| Option | Values | Default | What it does |",
          "| --- | --- | --- | --- |",
          ...options.map((o) => `| \`${o.id}\` | ${hint(o)} | \`${JSON.stringify(o.default)}\` | ${o.label}${o.help ? `. ${o.help}` : ""} |`),
        ]
      : []),
    "",
    "```sh",
    `toolmaster ${m.id} -i input${m.input.accept[0]} -o ${out}${exampleOption(options)}`,
    "```",
    "",
  ].join("\n");
}

/** TOOLS.md: the agent- and human-readable catalog, generated from manifests so it can never drift from the code. */
export function renderCatalog(manifests, catalog) {
  const sorted = [...manifests].sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
  return [
    "# ToolMaster tools",
    "",
    "<!-- Generated by `npm run catalog` from each tool's manifest. Do not edit by hand. -->",
    "",
    "Run a tool from a terminal: `toolmaster <id> -i <input> -o <output|-> [-O option=value] [--json]`.",
    "AI agents: `toolmaster mcp` serves every tool below over MCP, with the same names and options.",
    "`-o -` prints a text result to stdout. Exit codes: 0 ok, 2 bad input, 3 policy, 4 tool failed, 5 timeout, 6 engine missing, 7 busy.",
    "",
    "| Tool | Category | Reads | Writes |",
    "| --- | --- | --- | --- |",
    ...sorted.map((m) => `| ${m.name} \`${m.id}\` | ${m.category} | ${m.input.accept.join(" ")} | .${m.output.extension} |`),
    "",
    ...sorted.map((m) => section(m, catalog.forManifest(m))),
  ].join("\n");
}
